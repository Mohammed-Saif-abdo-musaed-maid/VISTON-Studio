/** A Bezier anchor point in layer-local space. `inX/inY` and `outX/outY` are
 *  the control-handle offsets relative to the anchor (0,0 = no handle). When
 *  `smooth` is set and a handle is missing it is derived from the segment
 *  neighbours. */
export interface PathPoint {
  x: number;
  y: number;
  inX: number;
  inY: number;
  outX: number;
  outY: number;
  smooth: boolean;
}

export interface ShapeLayer extends BaseLayer {
  type: "shape";
  shape: ShapeKind;
  fill: string | null;
  stroke: string | null;
  strokeWidth: number;
  /** Corner radius for roundedRect (px in local space). */
  cornerRadius: number;
  /** Number of sides for polygon / star. */
  points: number;
  /** Inner radius ratio (0..1) for stars. */
  starRatio: number;
  /** Anchor points for the "path" kind, in local (transform) space. When the
   *  first point equals the last point the path is closed (and is fillable). */
  pathPoints?: number[][] | null;
  /** Optional Bezier path data for the "path" kind. Written together with
   *  `pathPoints` so legacy projects and previews stay compatible. */
  pathData?: PathPoint[] | null;
}

export interface AdjustmentParams {
  brightness?: number;
  contrast?: number;
  gamma?: number;
  saturation?: number;
  exposure?: number;
  hue?: number;
  temperature?: number;
  vibrance?: number;
  colorBalance?: { shadows: number; midtones: number; highlights: number };
  levels?: { black: number; mid: number; white: number };
  curves?: number[][];
  equalize?: boolean;
  /** Tint: signed amount toward magenta (+) / green (−), −100..100. */
  tint?: number;
  /** Black & white: per-channel red/green/blue mixing weights. */
  blackWhite?: { red: number; green: number; blue: number };
  /** Channel mixer: output = r*R + g*G + b*B per channel (rows 0..1). */
  channelMixer?: {
    red: { r: number; g: number; b: number };
    green: { r: number; g: number; b: number };
    blue: { r: number; g: number; b: number };
  };
  /** Selective color: signed per-colour-region adjustment (−100..100). */
  selectiveColor?: {
    reds: number;
    yellows: number;
    greens: number;
    cyans: number;
    blues: number;
    magentas: number;
    whites: number;
    neutrals: number;
    blacks: number;
  };
  /** Gradient map: ordered luminance stops (pos 0..1, hex color). */
  gradientMap?: { stops: { pos: number; color: string }[] };
  /** Color lookup: identity / grayscale / invert / sepia built-ins. */
  colorLookup?: { lut: "identity" | "grayscale" | "invert" | "sepia" };
}

export interface AdjustmentLayer extends BaseLayer {
  type: "adjustment";
  adjustment: AdjustmentKind;
  amount: number;
  /** Extended parameters for levels/curves/color-balance style adjustments. */
  params: AdjustmentParams | null;
}

/**
 * 3D layer types. Each carries an `imageId` exactly like an ImageLayer: the
 * 3D runtime rasterizes the referenced scene/object into that pixelStore
 * buffer, so 2D compositing (masks, clips, blend modes, opacity) reuses the
 * existing pipeline verbatim. Non-destructive — the original scene stays
 * editable and re-rasterizes on demand.
 */
export interface Scene3DLayer extends BaseLayer {
  type: "3d-scene";
  sceneId: string;
  imageId: string;
}

export interface Object3DLayer extends BaseLayer {
  type: "3d-object";
  sceneId: string;
  objectId: string;
  imageId: string;
}

export interface Group3DLayer extends BaseLayer {
  type: "3d-group";
  sceneId: string;
  objectId: string;
  imageId: string;
}

export interface GroupLayer extends BaseLayer {
  type: "group";
  collapsed: boolean;
}

