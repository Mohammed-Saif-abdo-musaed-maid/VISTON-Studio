export type ProductSegmentOrigin = "none" | "ai" | "manual" | "mock" | "canvas";

/** Non-destructive metadata for a Product-Compositing layer. Lives on the
 *  ImageLayer; save/load round-trips it as plain JSON. */
export interface ProductCompositeMetadata {
  role: "product";
  sourceName: string | null;
  sourceWidth: number;
  sourceHeight: number;
  /** How the current cutout came to exist. */
  segmentOrigin: ProductSegmentOrigin;
  segmentOperation: string | null;
  segmentProvider: string | null;
  segmentModel: string | null;
  segmentPrompt: string | null;
  importedAt: number;
  /** Lighting values that were baked into the pixels (informational). */
  lighting: ProductLightingValues;
  /** Values baked by the color-match operation. */
  colorMatch: ProductLightingValues;
  /** Recorded when AI / smart-placement positioned the product. */
  smartPlace: { ai: boolean; operation: string | null; provider: string | null; x: number; y: number; width: number; height: number } | null;
  perspectiveMatched: { ai: boolean; operation: string | null; provider: string | null; skewX: number; skewY: number } | null;
  /** Pristine-source snapshot id (used so repeated lighting bakes stay stable). */
  sourceImageId: string | null;
}

