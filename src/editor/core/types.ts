export const LAYER_STYLE_KINDS: LayerStyleKind[] = [
  "dropShadow", "innerShadow", "outerGlow", "innerGlow", "stroke",
  "colorOverlay", "gradientOverlay", "bevel",
];

/** True when at least one style effect is present AND enabled. */
export function hasAnyStyle(styles: LayerStyles | null | undefined): boolean {
  if (!styles) return false;
  return LAYER_STYLE_KINDS.some((k) => styles[k] !== null && styles[k]!.enabled);
}

export function cloneLayerStyles(styles: LayerStyles | null | undefined): LayerStyles | null {
  if (!styles) return null;
  const out = emptyLayerStyles();
  const rec = out as Record<LayerStyleKind, LayerStyle | null>;
  for (const key of LAYER_STYLE_KINDS) {
    const v = styles[key];
    rec[key] = v ? { ...v } : null;
  }
  return out;
}

/** UI defaults for each effect type when the user first adds it. */
export function defaultLayerStyle(kind: LayerStyleKind): LayerStyle {
  switch (kind) {
    case "dropShadow":
      return { kind, enabled: true, offsetX: 0, offsetY: 4, blur: 6, color: "#000000", opacity: 0.4 };
    case "innerShadow":
      return { kind, enabled: true, offsetX: 0, offsetY: 4, blur: 5, color: "#000000", opacity: 0.4 };
    case "outerGlow":
      return { kind, enabled: true, blur: 8, spread: 0, color: "#7ab8ff", opacity: 0.6 };
    case "innerGlow":
      return { kind, enabled: true, blur: 8, spread: 0, color: "#7ab8ff", opacity: 0.6 };
    case "stroke":
      return { kind, enabled: true, color: "#000000", width: 2, position: "center", opacity: 1 };
    case "colorOverlay":
      return { kind, enabled: true, color: "#ff5a5a", opacity: 1 };
    case "gradientOverlay":
      return { kind, enabled: true, gradient: "linear", angle: 90, stops: [{ pos: 0, color: "#ffffff" }, { pos: 1, color: "#000000" }], opacity: 1 };
    case "bevel":
      return { kind, enabled: true, size: 5, angle: 120, depth: 0.5, highlightColor: "#ffffff", shadowColor: "#000000", opacity: 1 };
  }
}

